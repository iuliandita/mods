from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

from modslib.catalog import CatalogError, Mod, inject_span, load_all, load_mods, shared_dir

MARKETPLACE_NAME = "iuliandita-mods"
LOCAL_MARKETPLACE_NAME = "iuliandita-mods-local"
GITHUB_SOURCE = "iuliandita/mods"
OWNER = {"name": "iuliandita"}


def build_marketplace(mods: list[Mod], *, local: bool = False) -> dict:
    return {
        "name": LOCAL_MARKETPLACE_NAME if local else MARKETPLACE_NAME,
        "description": (
            "Private Claude Code mods, local only."
            if local
            else "Claude Code mods you can install one at a time."
        ),
        "owner": OWNER,
        "plugins": [
            {
                "name": m.name,
                "source": f"./mods/{m.name}/claude",
                "description": m.summary,
            }
            for m in sorted(mods, key=lambda m: m.name)
        ],
    }


def build_codex_marketplace(mods: list[Mod]) -> dict:
    return {
        "name": MARKETPLACE_NAME,
        "interface": {"displayName": "iuliandita mods"},
        "plugins": [
            {
                "name": m.name,
                "source": {"source": "local", "path": f"./mods/{m.name}/codex"},
                "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
                "category": "Developer Tools",
            }
            for m in sorted(mods, key=lambda m: m.name)
            if "codex" in m.hosts
        ],
    }


def host_install(mod: Mod) -> dict:
    out: dict[str, dict[str, str]] = {}
    if "codex" in mod.hosts:
        out["codex"] = {
            "install": f"codex plugin marketplace add {GITHUB_SOURCE} && codex plugin add {mod.name}@{MARKETPLACE_NAME}"
        }
    if "opencode" in mod.hosts:
        out["opencode"] = {
            "install": f'clone this repository and add {{"package": "<clone>/mods/{mod.name}/opencode"}} to "plugins" in opencode.json'
        }
    return out


def build_catalog(mods: list[Mod]) -> dict:
    return {
        "schema": 1,
        "marketplace": MARKETPLACE_NAME,
        "source": GITHUB_SOURCE,
        "mods": [
            {
                **{k: v for k, v in m.as_dict().items() if k != "hosts"},
                "install": (
                    f"claude plugin marketplace add {GITHUB_SOURCE} && "
                    f"claude plugin install {m.name}@{MARKETPLACE_NAME}"
                ),
                **({"hosts": host_install(m)} if m.hosts else {}),
            }
            for m in sorted(mods, key=lambda m: m.name)
        ],
    }


def render(obj: dict) -> str:
    return json.dumps(obj, indent=2) + "\n"


def shared_copy_dir(mod: Mod) -> Path:
    return mod.plugin_dir / "hooks" / "shared"


HEADER_PREFIX = "// Generated from shared/"


def shared_copy(root: Path, name: str) -> str:
    header = f"{HEADER_PREFIX}{name} by scripts/mods generate. Do not edit by hand.\n"
    return header + (shared_dir(root) / name).read_text()


def register_path(mod: Mod) -> Path:
    return mod.plugin_dir / "hooks" / "register.ts"


# The mod's register.ts with each listed block rewritten between its markers (checked by the catalog).
def injected(root: Path, mod: Mod) -> str:
    text = register_path(mod).read_text()
    for name in mod.inject:
        span = inject_span(text, name)
        if span is None:
            raise CatalogError(f"{mod.name}: inject markers for {name} are missing")
        block = (shared_dir(root) / name).read_text()
        if block and not block.endswith("\n"):
            block += "\n"
        text = text[: span[0]] + block + text[span[1] :]
    return text


# The host packages ship one self-contained file each, so a plugin copied out of the repository still runs.
HOST_BUNDLES = {"codex": ("host/bin.ts", "codex/bin/{name}.mjs"), "opencode": ("host/opencode.ts", "opencode/server.js")}


def pinned_bun(root: Path) -> str:
    return (root / ".bun-version").read_text().strip()


def bun_problem(root: Path) -> str | None:
    """Why the pinned bun is not usable here, or None when it is."""
    bun = shutil.which("bun")
    if bun is None:
        return f"bun {pinned_bun(root)} is required to build the host bundles (not found)"
    have = subprocess.run([bun, "--version"], capture_output=True, text=True, check=False).stdout.strip()
    if have != pinned_bun(root):
        return f"bun {pinned_bun(root)} is required to build the host bundles (found {have or 'none'})"
    return None


def bundle(root: Path, mod: Mod, host: str) -> str:
    entry, _ = HOST_BUNDLES[host]
    proc = subprocess.run(
        ["bun", "build", str(mod.path.relative_to(root) / entry), "--target=node", "--format=esm"],
        cwd=root,
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        raise CatalogError(f"{mod.name}: bun build of the {host} bundle failed:\n{proc.stderr.strip()}")
    header = f"// Generated by scripts/mods generate from mods/{mod.name}/host. Do not edit by hand.\n"
    return header + proc.stdout


def bundle_path(mod: Mod, host: str) -> Path:
    return mod.path / HOST_BUNDLES[host][1].format(name=mod.name)


def targets(root: Path, *, include_local: bool, bundles: bool = False) -> dict[Path, str]:
    mods = load_all(root, include_local=include_local)
    public = load_mods(root)
    out = {
        shared_copy_dir(m) / name: shared_copy(root, name) for m in mods for name in m.shared
    }
    out |= {register_path(m): injected(root, m) for m in mods if m.inject}
    if bundles:
        out |= {bundle_path(m, h): bundle(root, m, h) for m in mods for h in m.hosts}
    out |= {
        root / ".claude-plugin" / "marketplace.json": render(build_marketplace(public)),
        root / "mods.json": render(build_catalog(public)),
    }
    if any("codex" in m.hosts for m in public):
        out[root / ".agents" / "plugins" / "marketplace.json"] = render(build_codex_marketplace(public))
    if include_local:
        private = load_mods(root, local=True)
        out[root / "local" / ".claude-plugin" / "marketplace.json"] = render(
            build_marketplace(private, local=True)
        )
    return out


# Copies in a mod's hooks/shared/ that its mod.json no longer lists.
def extra_copies(root: Path, *, include_local: bool) -> list[Path]:
    return [
        p
        for m in load_all(root, include_local=include_local)
        if shared_copy_dir(m).is_dir()
        for p in sorted(shared_copy_dir(m).iterdir())
        if p.is_file() and p.name not in m.shared
    ]


# Host bundles need the pinned bun. Writing them always does; checking them does only when
# MODS_REQUIRE_BUN=1 (CI), so a machine without that bun can still install and validate, and
# `bundles=False` leaves them out entirely.
def generate(root: Path, *, check: bool = False, include_local: bool = False, bundles: bool = True) -> list[Path]:
    required = not check or os.environ.get("MODS_REQUIRE_BUN") == "1"
    with_bundles = bundles and any(m.hosts for m in load_all(root, include_local=include_local))
    if with_bundles:
        problem = bun_problem(root)
        if problem and required:
            raise CatalogError(problem)
        with_bundles = problem is None
    changed: list[Path] = []
    extras = extra_copies(root, include_local=include_local)
    foreign = [p for p in extras if not p.read_text().startswith(HEADER_PREFIX)]
    if foreign:
        raise CatalogError(
            "not a generated copy (no generated header), move or delete it by hand: "
            + ", ".join(str(p.relative_to(root)) for p in foreign)
        )
    for path in extras:
        changed.append(path)
        if not check:
            path.unlink()
    for path, text in targets(root, include_local=include_local, bundles=with_bundles).items():
        if not path.is_file() or path.read_text() != text:
            changed.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    return changed
